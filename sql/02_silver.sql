-- Silver Dynamic Tables — conform silos, TARGET_LAG 5 minutes

USE DATABASE AETHER_CARE;
USE SCHEMA SILVER;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE DYNAMIC TABLE PERSON_XWALK
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT
  x.MEMBER_ID,
  x.PATIENT_ID,
  m.FIRST_NAME,
  m.LAST_NAME,
  m.DOB,
  m.SEX,
  m.REGION,
  m.LINE_OF_BUSINESS,
  m.PANEL,
  m.PCP_NAME,
  m.PLAN_ID,
  p.MRN
FROM AETHER_CARE.BRONZE.MEMBER_PATIENT_XWALK x
JOIN AETHER_CARE.BRONZE.PAYER_MEMBERS m ON x.MEMBER_ID = m.MEMBER_ID
JOIN AETHER_CARE.BRONZE.EHR_PATIENTS p ON x.PATIENT_ID = p.PATIENT_ID;

CREATE OR REPLACE DYNAMIC TABLE CONDITIONS_ACTIVE
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT * FROM AETHER_CARE.BRONZE.EHR_CONDITIONS
WHERE LOWER(STATUS) = 'active';

CREATE OR REPLACE DYNAMIC TABLE MEDICATIONS_ACTIVE
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT
  *,
  LOWER(SPLIT_PART(DRUG_NAME, ' ', 1)) AS DRUG_KEY
FROM AETHER_CARE.BRONZE.EHR_MEDICATIONS
WHERE LOWER(STATUS) = 'active';

CREATE OR REPLACE DYNAMIC TABLE ENCOUNTERS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT
  *,
  LOWER(ENCOUNTER_CLASS) AS ENCOUNTER_CLASS_NORM,
  IFF(LOWER(UNPLANNED_READMIT_30D) IN ('true', '1', 'yes'), TRUE, FALSE) AS READMIT_30D
FROM AETHER_CARE.BRONZE.EHR_ENCOUNTERS;

CREATE OR REPLACE DYNAMIC TABLE LABS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT * FROM AETHER_CARE.BRONZE.EHR_LABS;

CREATE OR REPLACE DYNAMIC TABLE CLAIMS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT * FROM AETHER_CARE.BRONZE.PAYER_MEDICAL_CLAIMS;

ALTER TABLE AETHER_CARE.BRONZE.EHR_ENCOUNTERS SET CHANGE_TRACKING = TRUE;
ALTER TABLE AETHER_CARE.BRONZE.DOC_MANIFEST SET CHANGE_TRACKING = TRUE;
