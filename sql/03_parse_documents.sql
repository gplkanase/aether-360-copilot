USE DATABASE AETHER_CARE;
USE SCHEMA SILVER;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE TABLE PARSED_DOCUMENTS (
  DOC_ID STRING,
  FILENAME STRING,
  DOCUMENT_CLASS STRING,
  TITLE STRING,
  MEMBER_ID STRING,
  SERVICE_DATE DATE,
  NOTE_TYPE STRING,
  PARSE_MODE STRING,
  CONTENT STRING
);

-- Markdown/text files: ingest as VARCHAR. PDFs (if added later) use AI_PARSE_DOCUMENT.
INSERT OVERWRITE INTO PARSED_DOCUMENTS
SELECT
  m.DOC_ID,
  m.FILENAME,
  m.DOCUMENT_CLASS,
  m.TITLE,
  NULLIF(m.MEMBER_ID, ''),
  m.SERVICE_DATE,
  m.NOTE_TYPE,
  'TEXT_STAGE',
  TO_VARCHAR($1)
FROM @AETHER_CARE.RAW.DOCS_STAGE (FILE_FORMAT => (TYPE = CSV FIELD_DELIMITER = NONE SKIP_HEADER = 0 RECORD_DELIMITER = '\0'))
JOIN AETHER_CARE.BRONZE.DOC_MANIFEST m
  ON UPPER(METADATA$FILENAME) LIKE '%' || UPPER(m.FILENAME);

