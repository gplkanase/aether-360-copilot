CREATE OR REPLACE DYNAMIC TABLE DOC_CHUNKS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT
  p.DOC_ID || '-c' || LPAD(c.INDEX::STRING, 2, '0') AS CHUNK_ID,
  p.DOC_ID,
  p.DOCUMENT_CLASS,
  p.TITLE,
  p.MEMBER_ID,
  p.SERVICE_DATE,
  p.NOTE_TYPE,
  c.INDEX AS CHUNK_INDEX,
  c.VALUE::STRING AS CHUNK_TEXT
FROM PARSED_DOCUMENTS p,
LATERAL FLATTEN(
  INPUT => SNOWFLAKE.CORTEX.SPLIT_TEXT_RECURSIVE_CHARACTER(
    p.CONTENT, 'markdown', 1800, 300
  )
) c;
