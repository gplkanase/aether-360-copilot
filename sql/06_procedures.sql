-- Custom tools the Cortex Agent can call (actions, not just text)

USE DATABASE AETHER_CARE;
USE SCHEMA AGENTS;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE TABLE CARE_TICKETS (
  TICKET_ID STRING,
  TICKET_TYPE STRING,
  MEMBER_ID STRING,
  REASON STRING,
  OWNER STRING,
  STATUS STRING,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE PROCEDURE GET_MEMBER_360(MEMBER_ID STRING)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
  SELECT OBJECT_CONSTRUCT(
    'member', (SELECT OBJECT_CONSTRUCT(*) FROM AETHER_CARE.GOLD.MEMBER_360 WHERE MEMBER_ID = MEMBER_ID),
    'factors', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM AETHER_CARE.GOLD.ATRI_FACTORS WHERE MEMBER_ID = MEMBER_ID),
    'disclaimer', 'ATRI is a transparent rules index, not a mortality prediction. Synthetic data only.'
  )
$$;

CREATE OR REPLACE PROCEDURE OPEN_CARE_GAP_TICKET(MEMBER_ID STRING, REASON STRING, OWNER STRING)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
  INSERT INTO AETHER_CARE.AGENTS.CARE_TICKETS (TICKET_ID, TICKET_TYPE, MEMBER_ID, REASON, OWNER, STATUS)
  SELECT 'AETH-' || LPAD(COUNT(*)+1, 4, '0'), 'care_gap', MEMBER_ID, REASON, COALESCE(OWNER, 'care_manager'), 'open'
  FROM AETHER_CARE.AGENTS.CARE_TICKETS;
  RETURN 'opened';
END;
$$;
