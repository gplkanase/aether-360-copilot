-- Aether Care Alliance — database, warehouse, schemas, stage
-- Fully synthetic. Safe to recreate in a hackathon account.

CREATE WAREHOUSE IF NOT EXISTS AETHER_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Aether 360 copilot warehouse';

CREATE DATABASE IF NOT EXISTS AETHER_CARE
  COMMENT = 'Synthetic Patient/Member 360 and clinical-regulatory documents';

CREATE SCHEMA IF NOT EXISTS AETHER_CARE.RAW;
CREATE SCHEMA IF NOT EXISTS AETHER_CARE.BRONZE;
CREATE SCHEMA IF NOT EXISTS AETHER_CARE.SILVER;
CREATE SCHEMA IF NOT EXISTS AETHER_CARE.GOLD;
CREATE SCHEMA IF NOT EXISTS AETHER_CARE.AGENTS;
CREATE SCHEMA IF NOT EXISTS AETHER_CARE.APP;

CREATE STAGE IF NOT EXISTS AETHER_CARE.RAW.CSV_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Bronze CSV landing';

CREATE STAGE IF NOT EXISTS AETHER_CARE.RAW.DOCS_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Unstructured clinical and regulatory documents';

CREATE STAGE IF NOT EXISTS AETHER_CARE.APP.APP_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Streamlit app files';

USE DATABASE AETHER_CARE;
USE WAREHOUSE AETHER_WH;
