-- Gold Member 360 + ATRI factor ledger (must match aether360/risk.py)

USE DATABASE AETHER_CARE;
USE SCHEMA GOLD;
USE WAREHOUSE AETHER_WH;

-- As-of date is a literal so Dynamic Tables can refresh without session variables.
-- Must match aether360.risk.AS_OF.

CREATE OR REPLACE VIEW VW_ATRI_FACTORS AS
WITH members AS (
  SELECT * FROM AETHER_CARE.SILVER.PERSON_XWALK
),
age_f AS (
  SELECT
    MEMBER_ID,
    'AGE_85P' AS FACTOR_CODE, 20 AS POINTS, 'PAYER_MEMBERS' AS SOURCE_OBJECT,
    MEMBER_ID || ' / dob' AS SOURCE_KEY,
    'Age ' || DATEDIFF('year', DOB, DATE '2026-08-31') || ' (≥85)' AS EVIDENCE
  FROM members WHERE DATEDIFF('year', DOB, DATE '2026-08-31') >= 85
  UNION ALL
  SELECT MEMBER_ID, 'AGE_75_84', 14, 'PAYER_MEMBERS', MEMBER_ID || ' / dob',
         'Age ' || DATEDIFF('year', DOB, DATE '2026-08-31') || ' (75–84)'
  FROM members WHERE DATEDIFF('year', DOB, DATE '2026-08-31') BETWEEN 75 AND 84
  UNION ALL
  SELECT MEMBER_ID, 'AGE_65_74', 8, 'PAYER_MEMBERS', MEMBER_ID || ' / dob',
         'Age ' || DATEDIFF('year', DOB, DATE '2026-08-31') || ' (65–74)'
  FROM members WHERE DATEDIFF('year', DOB, DATE '2026-08-31') BETWEEN 65 AND 74
  UNION ALL
  SELECT MEMBER_ID, 'AGE_50_64', 4, 'PAYER_MEMBERS', MEMBER_ID || ' / dob',
         'Age ' || DATEDIFF('year', DOB, DATE '2026-08-31') || ' (50–64)'
  FROM members WHERE DATEDIFF('year', DOB, DATE '2026-08-31') BETWEEN 50 AND 64
),
dx AS (
  SELECT MEMBER_ID, ICD10, DESCRIPTION FROM AETHER_CARE.SILVER.CONDITIONS_ACTIVE
),
hcc AS (
  SELECT MEMBER_ID, 'HCC_CHF' AS FACTOR_CODE, 18 AS POINTS, 'EHR_CONDITIONS' AS SOURCE_OBJECT,
         MEMBER_ID || ' / ' || ICD10 AS SOURCE_KEY, DESCRIPTION || ' (active)' AS EVIDENCE
  FROM dx WHERE ICD10 ILIKE 'I50%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_CKD3P', 12, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 IN ('N18.3','N18.4','N18.5','N18.6') QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_T2DM', 6, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 ILIKE 'E11%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_COPD', 10, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 ILIKE 'J44%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_AFIB', 8, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 ILIKE 'I48%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_CAD', 8, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 ILIKE 'I25%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
  UNION ALL
  SELECT MEMBER_ID, 'HCC_DEP', 5, 'EHR_CONDITIONS', MEMBER_ID || ' / ' || ICD10, DESCRIPTION || ' (active)'
  FROM dx WHERE ICD10 ILIKE 'F32%' OR ICD10 ILIKE 'F33%' QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ICD10) = 1
),
med_counts AS (
  SELECT MEMBER_ID, COUNT(*) AS N_MEDS FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE GROUP BY 1
),
poly AS (
  SELECT MEMBER_ID, 'POLY_8P' AS FACTOR_CODE, 12 AS POINTS, 'EHR_MEDICATIONS' AS SOURCE_OBJECT,
         MEMBER_ID || ' / count=' || N_MEDS AS SOURCE_KEY, N_MEDS || ' active medications (polypharmacy ≥8)' AS EVIDENCE
  FROM med_counts WHERE N_MEDS >= 8
  UNION ALL
  SELECT MEMBER_ID, 'POLY_5_7', 6, 'EHR_MEDICATIONS', MEMBER_ID || ' / count=' || N_MEDS,
         N_MEDS || ' active medications (polypharmacy 5–7)'
  FROM med_counts WHERE N_MEDS BETWEEN 5 AND 7
),
ed AS (
  SELECT MEMBER_ID, COUNT(*) AS N_ED
  FROM AETHER_CARE.SILVER.ENCOUNTERS
  WHERE ENCOUNTER_CLASS_NORM = 'emergency'
    AND START_DATE >= DATEADD('day', -90, DATE '2026-08-31')
  GROUP BY 1
),
ed_f AS (
  SELECT MEMBER_ID, 'ED_90D' AS FACTOR_CODE, LEAST(24, 8 * N_ED) AS POINTS, 'EHR_ENCOUNTERS' AS SOURCE_OBJECT,
         MEMBER_ID || ' / ed90=' || N_ED AS SOURCE_KEY,
         N_ED || ' ED visit(s) in last 90 days (8 pts each, cap 24)' AS EVIDENCE
  FROM ed WHERE N_ED > 0
),
readmit AS (
  SELECT MEMBER_ID, ENCOUNTER_ID, START_DATE
  FROM AETHER_CARE.SILVER.ENCOUNTERS
  WHERE READMIT_30D
  QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY START_DATE DESC) = 1
),
readmit_f AS (
  SELECT MEMBER_ID, 'READMIT_30D' AS FACTOR_CODE, 20 AS POINTS, 'EHR_ENCOUNTERS' AS SOURCE_OBJECT,
         ENCOUNTER_ID AS SOURCE_KEY, 'Unplanned 30-day readmission on ' || START_DATE::STRING AS EVIDENCE
  FROM readmit
),
last_a1c AS (
  SELECT MEMBER_ID, LAB_ID, VALUE, RESULT_DATE
  FROM AETHER_CARE.SILVER.LABS
  WHERE LOINC = '4548-4' OR UPPER(TEST_CODE) = 'A1C'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY RESULT_DATE DESC) = 1
),
dm AS (
  SELECT DISTINCT MEMBER_ID FROM dx WHERE ICD10 ILIKE 'E11%'
),
gap_a1c AS (
  SELECT d.MEMBER_ID, 'GAP_A1C' AS FACTOR_CODE, 8 AS POINTS, 'EHR_LABS' AS SOURCE_OBJECT,
         COALESCE(a.LAB_ID, d.MEMBER_ID || ' / missing') AS SOURCE_KEY,
         IFF(a.LAB_ID IS NULL, 'Diabetes without any A1c on file',
             'Last A1c ' || a.VALUE || ' on ' || a.RESULT_DATE::STRING || ' (>6 months)') AS EVIDENCE
  FROM dm d
  LEFT JOIN last_a1c a ON d.MEMBER_ID = a.MEMBER_ID
  WHERE a.LAB_ID IS NULL OR a.RESULT_DATE < DATEADD('day', -180, DATE '2026-08-31')
),
pcp AS (
  SELECT DISTINCT MEMBER_ID
  FROM AETHER_CARE.SILVER.ENCOUNTERS
  WHERE ENCOUNTER_CLASS_NORM IN ('ambulatory', 'outpatient', 'pcp')
    AND START_DATE >= DATEADD('day', -365, DATE '2026-08-31')
),
gap_pcp AS (
  SELECT m.MEMBER_ID, 'GAP_PCP' AS FACTOR_CODE, 6 AS POINTS, 'EHR_ENCOUNTERS' AS SOURCE_OBJECT,
         m.MEMBER_ID || ' / no PCP 12m' AS SOURCE_KEY,
         'No ambulatory/PCP encounter in last 12 months' AS EVIDENCE
  FROM members m
  LEFT JOIN pcp p ON m.MEMBER_ID = p.MEMBER_ID
  WHERE p.MEMBER_ID IS NULL
),
cad AS (SELECT DISTINCT MEMBER_ID FROM dx WHERE ICD10 ILIKE 'I25%'),
statin AS (
  SELECT DISTINCT MEMBER_ID FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE
  WHERE DRUG_KEY IN ('atorvastatin','rosuvastatin','simvastatin','pravastatin','lovastatin','pitavastatin')
),
gap_statin AS (
  SELECT c.MEMBER_ID, 'GAP_STATIN_CAD' AS FACTOR_CODE, 7 AS POINTS, 'EHR_MEDICATIONS' AS SOURCE_OBJECT,
         c.MEMBER_ID || ' / CAD no statin' AS SOURCE_KEY,
         'CAD on problem list without an active statin' AS EVIDENCE
  FROM cad c
  LEFT JOIN statin s ON c.MEMBER_ID = s.MEMBER_ID
  WHERE s.MEMBER_ID IS NULL
),
cost AS (
  SELECT MEMBER_ID, SUM(ALLOWED_AMOUNT) AS ALLOWED_12M
  FROM AETHER_CARE.SILVER.CLAIMS
  GROUP BY 1
),
high_cost AS (
  SELECT MEMBER_ID, 'HIGH_COST' AS FACTOR_CODE, 10 AS POINTS, 'PAYER_MEDICAL_CLAIMS' AS SOURCE_OBJECT,
         MEMBER_ID || ' / allowed_12m=' || ALLOWED_12M::STRING AS SOURCE_KEY,
         'Allowed medical amount last 12m $' || ALLOWED_12M::STRING || ' (≥$50,000)' AS EVIDENCE
  FROM cost WHERE ALLOWED_12M >= 50000
),
warf AS (
  SELECT MEMBER_ID, RX_ID, DRUG_NAME FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE
  WHERE DRUG_KEY IN ('warfarin','jantoven')
),
nsaid AS (
  SELECT MEMBER_ID, RX_ID, DRUG_NAME FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE
  WHERE DRUG_KEY IN ('ibuprofen','naproxen','diclofenac','meloxicam','indomethacin')
),
warf_age AS (
  SELECT w.MEMBER_ID, 'WARF_AGE75' AS FACTOR_CODE, 9 AS POINTS, 'EHR_MEDICATIONS' AS SOURCE_OBJECT,
         w.RX_ID AS SOURCE_KEY,
         'Anticoagulated with ' || w.DRUG_NAME || ' at age ' || DATEDIFF('year', m.DOB, DATE '2026-08-31') AS EVIDENCE
  FROM warf w
  JOIN members m ON w.MEMBER_ID = m.MEMBER_ID
  WHERE DATEDIFF('year', m.DOB, DATE '2026-08-31') >= 75
  QUALIFY ROW_NUMBER() OVER (PARTITION BY w.MEMBER_ID ORDER BY w.RX_ID) = 1
),
ddi AS (
  SELECT w.MEMBER_ID, 'DDI_WARF_NSAID' AS FACTOR_CODE, 15 AS POINTS, 'EHR_MEDICATIONS' AS SOURCE_OBJECT,
         w.RX_ID || ' + ' || n.RX_ID AS SOURCE_KEY,
         'Warfarin + NSAID (' || n.DRUG_NAME || ') both active' AS EVIDENCE
  FROM warf w
  JOIN nsaid n ON w.MEMBER_ID = n.MEMBER_ID
  QUALIFY ROW_NUMBER() OVER (PARTITION BY w.MEMBER_ID ORDER BY w.RX_ID) = 1
)
SELECT * FROM age_f
UNION ALL SELECT * FROM hcc
UNION ALL SELECT * FROM poly
UNION ALL SELECT * FROM ed_f
UNION ALL SELECT * FROM readmit_f
UNION ALL SELECT * FROM gap_a1c
UNION ALL SELECT * FROM gap_pcp
UNION ALL SELECT * FROM gap_statin
UNION ALL SELECT * FROM high_cost
UNION ALL SELECT * FROM warf_age
UNION ALL SELECT * FROM ddi;

CREATE OR REPLACE DYNAMIC TABLE ATRI_FACTORS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT * FROM VW_ATRI_FACTORS;

CREATE OR REPLACE DYNAMIC TABLE MEMBER_360
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
WITH scores AS (
  SELECT MEMBER_ID,
         SUM(POINTS) AS RAW_SCORE,
         LEAST(100, SUM(POINTS)) AS ATRI_SCORE
  FROM VW_ATRI_FACTORS
  GROUP BY 1
),
dx_list AS (
  SELECT MEMBER_ID, LISTAGG(ICD10 || ' ' || DESCRIPTION, '; ') WITHIN GROUP (ORDER BY ICD10) AS ACTIVE_CONDITION_LIST
  FROM AETHER_CARE.SILVER.CONDITIONS_ACTIVE GROUP BY 1
),
rx_list AS (
  SELECT MEMBER_ID,
         LISTAGG(DRUG_NAME || ' (' || SIG || ')', '; ') WITHIN GROUP (ORDER BY DRUG_NAME) AS ACTIVE_MED_LIST,
         COUNT(*) AS ACTIVE_MED_COUNT
  FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE GROUP BY 1
),
ed90 AS (
  SELECT MEMBER_ID, COUNT(*) AS ED_VISITS_90D
  FROM AETHER_CARE.SILVER.ENCOUNTERS
  WHERE ENCOUNTER_CLASS_NORM = 'emergency' AND START_DATE >= DATEADD('day', -90, DATE '2026-08-31')
  GROUP BY 1
),
readmit AS (
  SELECT MEMBER_ID, MAX(IFF(READMIT_30D, TRUE, FALSE)) AS READMIT_30D_FLAG,
         MAX(START_DATE) AS LAST_ENCOUNTER_DATE
  FROM AETHER_CARE.SILVER.ENCOUNTERS
  GROUP BY 1
),
a1c AS (
  SELECT MEMBER_ID, VALUE AS LAST_A1C_VALUE, RESULT_DATE AS LAST_A1C_DATE
  FROM AETHER_CARE.SILVER.LABS
  WHERE LOINC = '4548-4' OR UPPER(TEST_CODE) = 'A1C'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY RESULT_DATE DESC) = 1
),
cost AS (
  SELECT MEMBER_ID, SUM(ALLOWED_AMOUNT) AS ALLOWED_12M
  FROM AETHER_CARE.SILVER.CLAIMS GROUP BY 1
),
gaps AS (
  SELECT MEMBER_ID,
         LISTAGG(IFF(FACTOR_CODE='GAP_A1C','GSD-A1c overdue',
                  IFF(FACTOR_CODE='GAP_PCP','No PCP 12m',
                  IFF(FACTOR_CODE='GAP_STATIN_CAD','CAD without statin', NULL))), '; ')
           WITHIN GROUP (ORDER BY FACTOR_CODE) AS OPEN_GAP_LIST
  FROM VW_ATRI_FACTORS
  WHERE FACTOR_CODE IN ('GAP_A1C','GAP_PCP','GAP_STATIN_CAD')
  GROUP BY 1
),
safety AS (
  SELECT MEMBER_ID,
         LISTAGG(IFF(FACTOR_CODE='DDI_WARF_NSAID','Warfarin + NSAID', NULL), '; ')
           WITHIN GROUP (ORDER BY FACTOR_CODE) AS SAFETY_FLAG_LIST
  FROM VW_ATRI_FACTORS
  WHERE FACTOR_CODE = 'DDI_WARF_NSAID'
  GROUP BY 1
),
sglt AS (
  SELECT DISTINCT MEMBER_ID FROM AETHER_CARE.SILVER.MEDICATIONS_ACTIVE
  WHERE DRUG_KEY IN ('empagliflozin','dapagliflozin','canagliflozin')
),
cov AS (
  SELECT MEMBER_ID, PRODUCT_NAME, HAS_METABOLIC_RIDER
  FROM AETHER_CARE.BRONZE.COVERAGE
)
SELECT
  m.MEMBER_ID,
  m.PATIENT_ID,
  m.FIRST_NAME || ' ' || m.LAST_NAME AS FULL_NAME,
  m.FIRST_NAME,
  m.LAST_NAME,
  m.DOB,
  DATEDIFF('year', m.DOB, DATE '2026-08-31') AS AGE_YEARS,
  m.SEX,
  m.REGION,
  m.LINE_OF_BUSINESS,
  m.PANEL,
  m.PCP_NAME,
  m.PLAN_ID,
  cov.PRODUCT_NAME,
  cov.HAS_METABOLIC_RIDER,
  COALESCE(s.ATRI_SCORE, 0) AS ATRI_SCORE,
  COALESCE(s.RAW_SCORE, 0) AS ATRI_SCORE_UNCAPPED,
  CASE
    WHEN COALESCE(s.ATRI_SCORE,0) <= 19 THEN 'Low'
    WHEN COALESCE(s.ATRI_SCORE,0) <= 39 THEN 'Moderate'
    WHEN COALESCE(s.ATRI_SCORE,0) <= 59 THEN 'High'
    ELSE 'Very High'
  END AS ATRI_TIER,
  dx.ACTIVE_CONDITION_LIST,
  rx.ACTIVE_MED_LIST,
  COALESCE(rx.ACTIVE_MED_COUNT, 0) AS ACTIVE_MED_COUNT,
  COALESCE(ed.ED_VISITS_90D, 0) AS ED_VISITS_90D,
  COALESCE(r.READMIT_30D_FLAG, FALSE) AS READMIT_30D_FLAG,
  g.OPEN_GAP_LIST,
  TRIM(COALESCE(sf.SAFETY_FLAG_LIST,'') || IFF(sg.MEMBER_ID IS NOT NULL, IFF(sf.SAFETY_FLAG_LIST IS NOT NULL, '; SGLT2 on profile — ketosis counseling', 'SGLT2 on profile — ketosis counseling'), '')) AS SAFETY_FLAG_LIST,
  r.LAST_ENCOUNTER_DATE,
  a.LAST_A1C_VALUE,
  a.LAST_A1C_DATE,
  COALESCE(c.ALLOWED_12M, 0) AS ALLOWED_12M,
  DATE '2026-08-31' AS AS_OF
FROM AETHER_CARE.SILVER.PERSON_XWALK m
LEFT JOIN scores s ON m.MEMBER_ID = s.MEMBER_ID
LEFT JOIN dx_list dx ON m.MEMBER_ID = dx.MEMBER_ID
LEFT JOIN rx_list rx ON m.MEMBER_ID = rx.MEMBER_ID
LEFT JOIN ed90 ed ON m.MEMBER_ID = ed.MEMBER_ID
LEFT JOIN readmit r ON m.MEMBER_ID = r.MEMBER_ID
LEFT JOIN a1c a ON m.MEMBER_ID = a.MEMBER_ID
LEFT JOIN cost c ON m.MEMBER_ID = c.MEMBER_ID
LEFT JOIN gaps g ON m.MEMBER_ID = g.MEMBER_ID
LEFT JOIN safety sf ON m.MEMBER_ID = sf.MEMBER_ID
LEFT JOIN sglt sg ON m.MEMBER_ID = sg.MEMBER_ID
LEFT JOIN cov ON m.MEMBER_ID = cov.MEMBER_ID;

CREATE OR REPLACE DYNAMIC TABLE CARE_GAPS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AETHER_WH
AS
SELECT MEMBER_ID,
       IFF(FACTOR_CODE='GAP_A1C','GSD-A1c', IFF(FACTOR_CODE='GAP_PCP','PCP-12m','CAD-statin')) AS MEASURE,
       'open' AS STATUS,
       EVIDENCE
FROM VW_ATRI_FACTORS
WHERE FACTOR_CODE IN ('GAP_A1C','GAP_PCP','GAP_STATIN_CAD');

CREATE OR REPLACE TABLE ATRI_SNAPSHOT (
  SNAPSHOT_TS TIMESTAMP_NTZ,
  MEMBER_ID STRING,
  ATRI_SCORE NUMBER,
  ATRI_TIER STRING
);
