USE DATABASE AETHER_CARE;
USE WAREHOUSE AETHER_WH;

-- Orphan keys must be 0
SELECT 'orphan_360_members' AS chk, COUNT(*) AS n
FROM AETHER_CARE.GOLD.MEMBER_360 m
LEFT JOIN AETHER_CARE.BRONZE.PAYER_MEMBERS p ON m.MEMBER_ID = p.MEMBER_ID
WHERE p.MEMBER_ID IS NULL;

SELECT 'orphan_conditions' AS chk, COUNT(*) AS n
FROM AETHER_CARE.BRONZE.EHR_CONDITIONS c
LEFT JOIN AETHER_CARE.BRONZE.PAYER_MEMBERS p ON c.MEMBER_ID = p.MEMBER_ID
WHERE p.MEMBER_ID IS NULL;

-- Hero: Jordan Hale is Very High and has DDI + readmit factors
SELECT MEMBER_ID, ATRI_SCORE, ATRI_TIER, SAFETY_FLAG_LIST, READMIT_30D_FLAG
FROM AETHER_CARE.GOLD.MEMBER_360
WHERE MEMBER_ID = 'MEM-10007';

SELECT FACTOR_CODE, POINTS, SOURCE_KEY
FROM AETHER_CARE.GOLD.ATRI_FACTORS
WHERE MEMBER_ID = 'MEM-10007'
ORDER BY POINTS DESC;

-- Statin gap hero
SELECT MEMBER_ID, OPEN_GAP_LIST, ACTIVE_MED_LIST
FROM AETHER_CARE.GOLD.MEMBER_360
WHERE MEMBER_ID = 'MEM-10021';

-- Document chunks exist for warfarin NSAID language
SELECT CHUNK_ID, LEFT(CHUNK_TEXT, 180)
FROM AETHER_CARE.SILVER.DOC_CHUNKS
WHERE CHUNK_TEXT ILIKE '%NSAID%' AND DOC_ID ILIKE '%WARFARIN%';

