-- Cortex Search services over clinical notes and regulatory/policy chunks

USE DATABASE AETHER_CARE;
USE SCHEMA AGENTS;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE CORTEX SEARCH SERVICE SEARCH_CLINICAL
  ON CHUNK_TEXT
  ATTRIBUTES DOC_ID, DOCUMENT_CLASS, TITLE, MEMBER_ID, SERVICE_DATE, NOTE_TYPE, CHUNK_ID
  WAREHOUSE = AETHER_WH
  TARGET_LAG = '1 hour'
  EMBEDDING_MODEL = 'snowflake-arctic-embed-m-v1.5'
  COMMENT = 'Synthetic clinical notes for Aether 360'
AS (
  SELECT CHUNK_ID, DOC_ID, DOCUMENT_CLASS, TITLE, MEMBER_ID, SERVICE_DATE, NOTE_TYPE, CHUNK_TEXT
  FROM AETHER_CARE.SILVER.DOC_CHUNKS
  WHERE DOCUMENT_CLASS = 'clinical_note'
);

CREATE OR REPLACE CORTEX SEARCH SERVICE SEARCH_REGULATORY
  ON CHUNK_TEXT
  ATTRIBUTES DOC_ID, DOCUMENT_CLASS, TITLE, MEMBER_ID, CHUNK_ID
  WAREHOUSE = AETHER_WH
  TARGET_LAG = '1 hour'
  EMBEDDING_MODEL = 'snowflake-arctic-embed-m-v1.5'
  COMMENT = 'Synthetic labels, NCD, PA, formulary, safety alerts'
AS (
  SELECT CHUNK_ID, DOC_ID, DOCUMENT_CLASS, TITLE, MEMBER_ID, CHUNK_TEXT
  FROM AETHER_CARE.SILVER.DOC_CHUNKS
  WHERE DOCUMENT_CLASS IN ('fda_label','cms_ncd','safety_alert','pa_policy','formulary','quality_spec')
);
