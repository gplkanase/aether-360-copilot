-- Bronze: siloed EHR vs payer landing tables (synthetic)

USE DATABASE AETHER_CARE;
USE SCHEMA BRONZE;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE TABLE PAYER_MEMBERS (
  MEMBER_ID STRING,
  FIRST_NAME STRING,
  LAST_NAME STRING,
  DOB DATE,
  SEX STRING,
  REGION STRING,
  LINE_OF_BUSINESS STRING,
  PANEL STRING,
  PCP_NAME STRING,
  PLAN_ID STRING
);

CREATE OR REPLACE TABLE EHR_PATIENTS (
  PATIENT_ID STRING,
  GIVEN_NAME STRING,
  FAMILY_NAME STRING,
  BIRTH_DATE DATE,
  SEX STRING,
  CLINIC_REGION STRING,
  PCP_NAME STRING,
  MRN STRING
);

CREATE OR REPLACE TABLE MEMBER_PATIENT_XWALK (
  MEMBER_ID STRING,
  PATIENT_ID STRING,
  MATCH_METHOD STRING,
  MATCH_CONFIDENCE FLOAT
);

CREATE OR REPLACE TABLE COVERAGE (
  COVERAGE_ID STRING,
  MEMBER_ID STRING,
  PLAN_ID STRING,
  LINE_OF_BUSINESS STRING,
  PRODUCT_NAME STRING,
  EFFECTIVE_DATE DATE,
  TERM_DATE DATE,
  HAS_METABOLIC_RIDER STRING
);

CREATE OR REPLACE TABLE EHR_CONDITIONS (
  CONDITION_ID STRING,
  MEMBER_ID STRING,
  PATIENT_ID STRING,
  ICD10 STRING,
  DESCRIPTION STRING,
  STATUS STRING,
  ONSET_DATE DATE,
  SOURCE_SYSTEM STRING
);

CREATE OR REPLACE TABLE EHR_MEDICATIONS (
  RX_ID STRING,
  MEMBER_ID STRING,
  PATIENT_ID STRING,
  DRUG_NAME STRING,
  DRUG_CLASS STRING,
  SIG STRING,
  STATUS STRING,
  START_DATE DATE,
  PRESCRIBER STRING,
  SOURCE_SYSTEM STRING
);

CREATE OR REPLACE TABLE EHR_ENCOUNTERS (
  ENCOUNTER_ID STRING,
  MEMBER_ID STRING,
  PATIENT_ID STRING,
  ENCOUNTER_CLASS STRING,
  START_DATE DATE,
  END_DATE DATE,
  REASON STRING,
  UNPLANNED_READMIT_30D STRING,
  FACILITY STRING,
  SOURCE_SYSTEM STRING,
  ALLOWED_HINT NUMBER(18,2)
);

CREATE OR REPLACE TABLE EHR_LABS (
  LAB_ID STRING,
  MEMBER_ID STRING,
  PATIENT_ID STRING,
  LOINC STRING,
  TEST_CODE STRING,
  TEST_NAME STRING,
  VALUE STRING,
  UNITS STRING,
  RESULT_DATE DATE,
  SOURCE_SYSTEM STRING
);

CREATE OR REPLACE TABLE PAYER_MEDICAL_CLAIMS (
  CLAIM_ID STRING,
  MEMBER_ID STRING,
  CLAIM_DATE DATE,
  CPT STRING,
  DX_PRINCIPAL STRING,
  ALLOWED_AMOUNT NUMBER(18,2),
  PLACE_OF_SERVICE STRING,
  CLAIM_TYPE STRING,
  SOURCE_SYSTEM STRING
);

CREATE OR REPLACE TABLE PAYER_PHARMACY_CLAIMS (
  RX_CLAIM_ID STRING,
  MEMBER_ID STRING,
  FILL_DATE DATE,
  DRUG_NAME STRING,
  DAYS_SUPPLY NUMBER,
  ALLOWED_AMOUNT NUMBER(18,2),
  SOURCE_SYSTEM STRING
);

CREATE OR REPLACE TABLE DOC_MANIFEST (
  DOC_ID STRING,
  DOCUMENT_CLASS STRING,
  TITLE STRING,
  FILENAME STRING,
  MEMBER_ID STRING,
  SERVICE_DATE DATE,
  NOTE_TYPE STRING
);

