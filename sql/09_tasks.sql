-- Streams, incremental-friendly change tracking, and scheduled ATRI snapshot

USE DATABASE AETHER_CARE;
USE WAREHOUSE AETHER_WH;

CREATE OR REPLACE STREAM AETHER_CARE.SILVER.PARSED_DOC_STREAM
  ON TABLE AETHER_CARE.SILVER.PARSED_DOCUMENTS;

CREATE OR REPLACE TASK AETHER_CARE.GOLD.ATRI_NIGHTLY_REFRESH
  WAREHOUSE = AETHER_WH
  SCHEDULE = 'USING CRON 0 6 * * * UTC'
  COMMENT = 'Unattended ATRI snapshot for the copilot as-of history'
AS
INSERT INTO AETHER_CARE.GOLD.ATRI_SNAPSHOT (SNAPSHOT_TS, MEMBER_ID, ATRI_SCORE, ATRI_TIER)
SELECT CURRENT_TIMESTAMP(), MEMBER_ID, ATRI_SCORE, ATRI_TIER
FROM AETHER_CARE.GOLD.MEMBER_360;

